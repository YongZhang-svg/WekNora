"""Render a Mermaid .mmd file to an image (PNG/SVG) or HTML.

Rendering strategy (in priority order):
1. mmdc (Mermaid CLI) — if available, renders directly to PNG/SVG
2. HTML fallback — generates a self-contained HTML file for browser viewing

Usage:
    # From file:
    python scripts/render_diagram.py <input.mmd> [--output <output>] [--format png|svg|html]

    # From stdin (for sandbox use where workspace is read-only):
    echo 'mindmap\n  root((Topic))' | python scripts/render_diagram.py --stdin [--name diagram] [--format png]

Sandbox notes:
- When running in Docker sandbox, the workspace is mounted read-only.
- Use --stdin mode with the 'input' parameter of execute_skill_script to pass
  Mermaid content directly without needing to create a file first.
- Output files are written to /output (if mounted) or /tmp.
- mmdc requires `-p /etc/mermaid-cli/puppeteer-config.json` in sandbox.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import shutil
import subprocess
import sys


